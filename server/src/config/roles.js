/**
 * Helper to compute effective permissions for an array of assigned roles
 * @param {string[]} userRoles - List of roles assigned to a user
 * @returns {string[]} Combined unique permissions
 */
export const getPermissionsForRoles = (userRoles = []) => {
  const permSet = new Set();
  userRoles.forEach((role) => {
    const perms = ROLE_PERMISSIONS[role] || [];
    perms.forEach((p) => permSet.add(p));
  });
  return Array.from(permSet);
};
